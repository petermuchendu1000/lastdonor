/** The graphics a given route should render, in registry order. */
export function brandGraphicsFor(page: string): BrandGraphic[] {
  return BRAND_GRAPHICS.filter((g) => g.page === page);
}

/** Site-root-relative path to the generated file. */
export function brandGraphicPath(slug: string): string {
  return `/images/explainers/${slug}.webp`;
}

/**
 * Every page that renders at least one graphic, for the sitemap.
 *
 * Derived rather than listed, so adding a graphic to a page cannot leave the
 * sitemap advertising the old set.
 */
export function pagesWithBrandGraphics(): string[] {
  return [...new Set(BRAND_GRAPHICS.map((g) => g.page))];
}
