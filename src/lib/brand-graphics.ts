/**
 * The published brand explainer graphics, and the page each one lives on.
 *
 * ── WHY THIS IS A REGISTRY AND NOT EIGHT `<Image>` TAGS ─────────────────────
 *
 * Three surfaces need the same answer and must not drift:
 *
 *   1. `<BrandGraphic>` renders the image and its alt text on a page.
 *   2. `sitemap.ts` advertises it to Google as an image belonging to that URL.
 *   3. `brand-graphics.test.ts` checks the file exists and the claims hold.
 *
 * If the alt text lived in the JSX and the sitemap built its own list, the
 * two would disagree the first time one was edited - which is the shape
 * `docs/138`, `docs/146` and `docs/165` all record.
 *
 * ⛔ **AN IMAGE ON NO PAGE IS NEVER INDEXED.** Google Images indexes images it
 * finds on pages it has crawled, so `page` is not decoration: a graphic
 * without one reaches nobody, however good it looks. A test fails the build
 * if any entry names a route that does not exist on disk.
 *
 * The files are generated by `scripts/generate-brand-graphics.ts`, which
 * imports THIS list for its slugs and alt text and owns only the visual
 * design. See `docs/171`.
 */

export interface BrandGraphic {
  /** Matches `public/images/explainers/<slug>.webp` and the generator's design key. */
  slug: string;
  /**
   * Describes the IMAGE, for a reader who cannot see it and for a crawler
   * deciding what it depicts. Not a slogan.
   */
  alt: string;
  /** Rendered beneath the image. Context a reader and a crawler both use. */
  caption: string;
  /** The route that renders it. */
  page: string;
}

