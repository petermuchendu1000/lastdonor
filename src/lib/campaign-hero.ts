/**
 * Which image stands at the top of a campaign, and what it is called.
 *
 * ── THE DEFECT THIS EXISTS FOR ──────────────────────────────────────────────
 *
 * [VERIFIED 2026-11-04 by classifying every `<img>` on the live `/campaigns`]
 * 8 of 10 published campaigns rendered a photograph of somebody who is not
 * the person named beside it:
 *
 *   7  Unsplash stock photos  (stored in `campaigns.hero_image_url`)
 *   1  generic category SVG
 *   2  photographs the organiser actually supplied
 *
 * Two were plainly wrong - a toddler holding a toy camera under *"Keisha
 * Wallace Fights to Keep Her Four Kids Off Atlanta Streets"*, and a male
 * doctor in a studio portrait under *"Help Danielle Sutton Care for Her
 * Twins While Battling Aggressive MS"*. `docs/36` is this project's recorded
 * history of forged attribution about real named people, and `docs/141` §5
 * raised this exact question and left it open.
 *
 * Owner decision 2026-11-04: a campaign with no photograph FROM ITS OWN
 * ORGANISER shows a designed brand panel, which depicts nobody.
 *
 * ── WHY THE DECISION IS MADE HERE AND NOT IN AN `onError` HANDLER ───────────
 *
 * ⛔ `CampaignHeroImage` used to swap in a stock photo from a curated pool
 * inside `onError`, which runs ONLY IN A BROWSER. A crawler reads the
 * server-rendered HTML, so it never saw that swap at all - every stock URL
 * Google would index came straight out of the database. A fix that lives in
 * an error handler changes nothing about what is indexed, which is the whole
 * point of the change. So this is a pure function, called while rendering.
 *
 * ── THE PREDICATE CAN ONLY FAIL ONE WAY ─────────────────────────────────────
 *
 * `isOrganiserPhoto` asks *"did WE receive this file from the organiser"*,
 * answered by where it is hosted: our own Supabase public media bucket and
 * nowhere else. Anything unrecognised - a new CDN, a malformed URL, a host
 * we cannot resolve - reads as NOT theirs and renders the panel. So the
 * worst case is a real photograph replaced by a panel, never a stranger's
 * face under a real person's name. That asymmetry is deliberate; do not
 * "improve" it into a denylist of stock-photo hosts, which fails the other
 * way the moment somebody adds a source nobody listed.
 */
import { CATEGORY_LABELS } from '@/lib/categories';
import type { CampaignCategory } from '@/types';

/**
 * Where an organiser's own upload lives.
 *
 * ⚠️ The bucket segment is written out rather than imported, because
 * `supabase-storage.ts` constructs a client and this module is reachable
 * from a client component. `campaign-hero.test.ts` asserts this string
 * against the real `BUCKET_NAME`, so the two cannot drift.
 */
export const PUBLIC_MEDIA_PREFIX = '/storage/v1/object/public/media/';

/** Used when a campaign carries a category this build does not know. */
export const FALLBACK_CATEGORY: CampaignCategory = 'community';

function knownCategory(category: string | null | undefined): CampaignCategory {
  const raw = (category ?? '').trim();
  return raw in CATEGORY_LABELS ? (raw as CampaignCategory) : FALLBACK_CATEGORY;
}

/** The designed brand panel for a category. Generated by `scripts/generate-category-panels.ts`. */
export function categoryPanelPath(category: string | null | undefined): string {
  return `/images/categories/${knownCategory(category)}-panel.webp`;
}

/**
 * Did this image come from the campaign's own organiser?
 *
 * True only for an https URL on our Supabase host whose path is the public
 * media bucket. A relative path is a site asset (category art), never an
 * upload, so it is false.
 */
export function isOrganiserPhoto(heroImageUrl: string | null | undefined): boolean {
  const raw = (heroImageUrl ?? '').trim();
  if (!raw) return false;

  let parsed: URL;
  try {
    parsed = new URL(raw);
  } catch {
    // Relative, empty, or malformed - none of which is an upload.
    return false;
  }

  if (parsed.protocol !== 'https:') return false;
  if (!parsed.pathname.startsWith(PUBLIC_MEDIA_PREFIX)) return false;

  /*
    `NEXT_PUBLIC_SUPABASE_URL` is inlined at build time, so it is readable
    from a client component. When it is absent (unit tests, a build with no
    Supabase configured) fall back to the registrable suffix rather than
    accepting any host that happens to use Supabase's path shape.
  */
  const configured = (process.env.NEXT_PUBLIC_SUPABASE_URL ?? '').trim();
  if (configured) {
    try {
      return parsed.host === new URL(configured).host;
    } catch {
      return false;
    }
  }
  return parsed.host.endsWith('.supabase.co');
}

export interface CampaignHero {
  /** The image to render. */
  src: string;
  /** True when `src` is a designed panel rather than a photograph of this campaign. */
  isPanel: boolean;
  /** Accessible name describing what the image actually is. */
  alt: string;
}

/**
 * Resolve a campaign's hero image and its accessible name together.
 *
 * ⚠️ The alt text moves with the image, which is the reason they are decided
 * in one place. A panel captioned *"Keisha Wallace Fights to Keep Her Four
 * Kids Off Atlanta Streets"* describes a teal graphic as a photograph of a
 * named person - the same class of inaccuracy, one layer down. So a panel is
 * named for what it is. The campaign title is still the adjacent heading on
 * every surface that renders this, so no context is lost for a reader or a
 * crawler.
 */
export function resolveCampaignHero(input: {
  heroImageUrl: string | null | undefined;
  category: string | null | undefined;
  title: string;
}): CampaignHero {
  const { heroImageUrl, category, title } = input;

  if (isOrganiserPhoto(heroImageUrl)) {
    return { src: (heroImageUrl ?? '').trim(), isPanel: false, alt: title };
  }

  return {
    src: categoryPanelPath(category),
    isPanel: true,
    alt: `LastDonor ${CATEGORY_LABELS[knownCategory(category)]} campaign`,
  };
}
