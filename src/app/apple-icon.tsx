import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { ImageResponse } from 'next/og';

/*
  The iOS home-screen icon.

  ## Why this reads a font off disk

  It used to ask for `fontFamily: 'Georgia, serif'` and supply no font
  data. `ImageResponse` renders through Satori, which has no system fonts
  at all — it uses only what it is handed — so the request for Georgia
  fell through to Satori's built-in sans. The live icon was thin
  sans-serif "LD." while the favicon and the BIMI logo (docs/95) are a
  bold serif. Nothing failed; it just quietly was not the brand.

  Embedding the real face is what fixes it, and it has to be read rather
  than named. That is also why the runtime is `nodejs` and not `edge`:
  the edge runtime has no filesystem.

  ## Why there are no rounded corners here

  iOS masks an apple-touch-icon to its own squircle. Supplying our own
  radius means the mask cuts a rounded shape out of an already rounded
  one, and the gap between the two shows whatever is behind — the old
  version was RGBA with transparent corners, so that gap was
  transparent. A full-bleed opaque square is what Apple's guidance asks
  for and what survives the mask cleanly.

  The browser favicon keeps its radius, because nothing masks that one:
  see `src/app/icon.svg`, generated by `scripts/generate-bimi-logo.py`.
*/

export const runtime = 'nodejs';
export const size = { width: 180, height: 180 };
export const contentType = 'image/png';

const BRAND_TEAL = '#0F766E';
const BRAND_AMBER = '#D97706';

export default async function AppleIcon() {
  const serif = readFileSync(
    join(process.cwd(), 'public', 'fonts', 'DMSerifDisplay-Regular.ttf'),
  );

  return new ImageResponse(
    (
      <div
        style={{
          width: '100%',
          height: '100%',
          display: 'flex',
          alignItems: 'center',
          justifyContent: 'center',
          background: BRAND_TEAL,
        }}
      >
        <span style={{ fontSize: 96, color: '#FFFFFF', fontFamily: 'DM Serif Display' }}>
          LD
        </span>
        <span style={{ fontSize: 96, color: BRAND_AMBER, fontFamily: 'DM Serif Display' }}>
          .
        </span>
      </div>
    ),
    {
      ...size,
      fonts: [{ name: 'DM Serif Display', data: serif, style: 'normal', weight: 400 }],
    },
  );
}
